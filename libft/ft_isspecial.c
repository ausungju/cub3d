#include "libft.h"

int	ft_isspecial(int c)
{
	return ((c >= '!' && c <= '/') || \
		(c >= ':' && c <= '@') || \
		(c >= '[' && c <= '`') || \
		(c >= '{' && c <= '~'));
}
